/** Stable UUID derived from a name, so ids are the same on every run and machine. */
export function seedUuid(name: string): string {
  const h = createHash("sha256").update(`remaxx-seed:${name}`).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-8${h.slice(17, 20)}-${h.slice(20, 32)}`;
}

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const sha = (b: Uint8Array) => createHash("sha256").update(b).digest("hex");

export type LoadedTemplate = SeedTemplate & {
  files: UploadFile[];
  entryPath: string;
  totalBytes: number;
};

/** Reads and validates every template exactly as an upload would be validated. */
export async function loadSeedTemplates(dir = SEED_DIR): Promise<LoadedTemplate[]> {
  const out: LoadedTemplate[] = [];
  for (const t of SEED_TEMPLATES) {
    const root = path.join(dir, t.slug);
    const names = await listFiles(root);
    const entries = await Promise.all(
      names.map(async (rel) => ({
        path: rel,
        bytes: new Uint8Array(await readFile(path.join(root, rel))),
      })),
    );
    const res = validateUpload(entries);
    if (!res.ok)
      throw new Error(
        `Seed template ${t.slug} is invalid: ${res.issues.map((i) => i.message).join("; ")}`,
      );
    const scan = scanFiles(res.files);
    if (scan.blocking.length || scan.flags.length) {
      throw new Error(
        `Seed template ${t.slug} trips the scanner: ${[...scan.blocking, ...scan.flags].map((f) => f.rule).join(", ")}`,
      );
    }
    out.push({ ...t, files: res.files, entryPath: res.entryPath, totalBytes: res.totalBytes });
  }
  return out;
}

async function listFiles(root: string, prefix = ""): Promise<string[]> {
  const entries = await readdir(path.join(root, prefix), { withFileTypes: true });
  const files: string[] = [];
  for (const e of entries) {
    const rel = prefix ? `${prefix}/${e.name}` : e.name;
    if (e.isDirectory()) files.push(...(await listFiles(root, rel)));
    else files.push(rel);
  }
  return files.sort();
}

export async function buildSeedSql(templates?: LoadedTemplate[]): Promise<string> {
  const list = templates ?? (await loadSeedTemplates());
  const bySlug = new Map(list.map((t) => [t.slug, t]));
  const sql: string[] = [
    "-- REMAXX starter templates. Generated by `pnpm seed:sql`; safe to run more than once.",
    "begin;",
    "",
    "-- Official studio account (works with Supabase's auth.users and the test stub).",
    "do $seed$ begin",
    "  if exists (select 1 from information_schema.columns where table_schema = 'auth' and table_name = 'users' and column_name = 'aud') then",
    "    insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,",
    "      raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, recovery_token,",
    "      email_change_token_new, email_change)",
    `    values ('00000000-0000-0000-0000-000000000000', ${q(STUDIO.id)}, 'authenticated', 'authenticated', ${q(STUDIO.email)}, '', now(),`,
    `      '{"provider":"email","providers":["email"]}', '{}', now(), now(), '', '', '', '')`,
    "    on conflict (id) do nothing;",
    "  else",
    `    insert into auth.users (id, email) values (${q(STUDIO.id)}, ${q(STUDIO.email)}) on conflict (id) do nothing;`,
    "  end if;",
    "end $seed$;",
    `insert into profiles (id, handle, display_name, bio, age_confirmed_at)`,
    `values (${q(STUDIO.id)}, ${q(STUDIO.handle)}, ${q(STUDIO.displayName)}, ${q(STUDIO.bio)}, now())`,
    "on conflict (id) do nothing;",
    "",
  ];

  const searchRows: string[] = [];

  // Parents before remixes.
  const ordered = [...list].sort((a, b) => depth(a) - depth(b));
  function depth(t: SeedTemplate): number {
    return t.parent ? 1 + depth(bySlug.get(t.parent)!) : 0;
  }

  for (const t of ordered) {
    const pid = seedUuid(`project:${t.slug}`);
    const vid = seedUuid(`version:${t.slug}`);
    const rank = FEED_ORDER.indexOf(t.slug);
    const hoursAgo = (rank === -1 ? FEED_ORDER.length : rank) * 3 + 1;
    const parent = t.parent ? bySlug.get(t.parent) : undefined;
    if (t.parent && !parent)
      throw new Error(`Seed template ${t.slug} has unknown parent ${t.parent}`);
    const parentId = parent ? seedUuid(`project:${parent.slug}`) : null;
    const rootSlug = rootOf(t);
    const rootId = parent ? seedUuid(`project:${rootSlug}`) : null;

    sql.push(`-- ${t.slug}`);
    for (const f of t.files) {
      const b64 = Buffer.from(f.bytes).toString("base64");
      sql.push(
        `insert into blobs (sha256, size, content) values (${q(sha(f.bytes))}, ${f.bytes.byteLength}, decode(${q(b64)}, 'base64')) on conflict do nothing;`,
      );
    }
    sql.push(
      `insert into projects (id, owner_id, slug, title, description, project_type, category, tool_used, license_id, status, cover_url, entry_path, parent_project_id, root_project_id, published_at, created_at)`,
      `values (${q(pid)}, ${q(STUDIO.id)}, ${q(t.slug)}, ${q(t.title)}, ${q(t.description)}, 'static', ${q(t.category)}, ${q(t.tool)}, ${q(t.license)}, 'published', ${q(`/seed/covers/${t.slug}.jpg`)}, ${q(t.entryPath)}, ${parentId ? q(parentId) : "null"}, ${rootId ? q(rootId) : "null"}, now() - interval '${hoursAgo} hours', now() - interval '${hoursAgo} hours')`,
      `on conflict (id) do nothing;`,
      `insert into project_versions (id, project_id, number, message, created_by, file_count, total_bytes, created_at)`,
      `values (${q(vid)}, ${q(pid)}, 1, ${q(parent ? "Remixed" : "First upload")}, 'system', ${t.files.length}, ${t.totalBytes}, now() - interval '${hoursAgo} hours')`,
      `on conflict (id) do nothing;`,
      `update projects set current_version_id = ${q(vid)}${parentId ? `, parent_version_id = ${q(seedUuid(`version:${parent!.slug}`))}` : ""} where id = ${q(pid)} and current_version_id is null;`,
    );
    for (const f of t.files) {
      sql.push(
        `insert into project_files (version_id, path, blob_sha256, size, mime) values (${q(vid)}, ${q(f.path)}, ${q(sha(f.bytes))}, ${f.bytes.byteLength}, ${q(f.mime)}) on conflict do nothing;`,
      );
    }
    const tagRows = [
      ...t.styles.map((s) => `(${q(s)}, 'style')`),
      ...t.tags.filter((x) => !(t.styles as string[]).includes(x)).map((s) => `(${q(s)}, 'topic')`),
    ];
    if (tagRows.length) {
      sql.push(
        `insert into tags (slug, kind) values ${tagRows.join(", ")} on conflict (slug) do nothing;`,
      );
      sql.push(
        `insert into project_tags (project_id, tag_id) select ${q(pid)}, id from tags where slug in (${[...t.styles, ...t.tags].map(q).join(", ")}) on conflict do nothing;`,
      );
    }
    // Search index row with the hand-written look-and-feel. The app adds the embedding later.
    const vibe = SEED_VIBES[t.slug];
    if (!vibe) throw new Error(`Seed template ${t.slug} has no entry in seed/vibes.ts`);
    const searchText = buildSearchText({
      title: t.title,
      description: t.description,
      category: t.category,
      toolUsed: t.tool,
      styles: t.styles,
      tags: t.tags.filter((x) => !(t.styles as string[]).includes(x)),
      styleDescription: vibe,
    });
    searchRows.push(
      `insert into project_search (project_id, version_id, style_description, style_source, search_text) ` +
        `values (${q(pid)}, ${q(vid)}, ${q(vibe)}, 'seed', ${q(searchText)}) ` +
        `on conflict (project_id) do update set version_id = excluded.version_id, style_description = excluded.style_description, search_text = excluded.search_text, style_source = 'seed' where project_search.style_source = 'seed';`,
    );
    sql.push(
      `insert into rights_attestations (project_id, user_id, license_id, statement_version)`,
      `select ${q(pid)}, ${q(STUDIO.id)}, ${q(t.license)}, ${q(RIGHTS_STATEMENT_VERSION)} where not exists (select 1 from rights_attestations where project_id = ${q(pid)});`,
    );

    // Lineage: closure rows plus a credit snapshot, nearest ancestor first.
    let ancestor = parent;
    let position = 1;
    while (ancestor) {
      const aid = seedUuid(`project:${ancestor.slug}`);
      sql.push(
        `insert into remix_lineage (ancestor_id, descendant_id, depth) values (${q(aid)}, ${q(pid)}, ${position}) on conflict do nothing;`,
      );
      sql.push(
        `insert into lineage_credits (project_id, position, ancestor_project_id, ancestor_title, ancestor_slug, ancestor_owner_handle, ancestor_license_id)`,
        `values (${q(pid)}, ${position}, ${q(aid)}, ${q(ancestor.title)}, ${q(ancestor.slug)}, ${q(STUDIO.handle)}, ${q(ancestor.license)}) on conflict do nothing;`,
      );
      ancestor = ancestor.parent ? bySlug.get(ancestor.parent) : undefined;
      position++;
    }
    sql.push("");
  }

  function rootOf(t: SeedTemplate): string {
    return t.parent ? rootOf(bySlug.get(t.parent)!) : t.slug;
  }

  sql.push(
    "commit;",
    "",
    // Search rows only if the vibe search table exists (setup SQL run first); otherwise skip.
    "do $search$ begin",
    "  if to_regclass('public.project_search') is null then",
    "    raise notice 'Vibe search table not found: run the setup SQL, then this seed again.';",
    "    return;",
    "  end if;",
    ...searchRows.map((r) => `  execute $row$${r}$row$;`),
    "end $search$;",
    "select count(*) as starter_templates from projects where owner_id = " + q(STUDIO.id) + ";",
  );
  return sql.join("\n") + "\n";
}
