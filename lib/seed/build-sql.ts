/**
 * Builds one idempotent SQL script that loads the starter templates. Running it twice changes
 * nothing. Used by `pnpm seed` (applies it) and `pnpm seed:sql` (prints it for the Supabase SQL
 * editor), and by tests, so all three load exactly the same data.
 */
