/**
 * Builds one SQL script that sets up a fresh Supabase project: a repair for starter-template
 * leftovers, a pre-check for name clashes, every migration in db/migrations (each guarded so it
 * runs once), the rows that mark them applied, and the storage buckets from config/limits.ts.
 * Re-running it on an already set-up project is safe.
 */
import { readFile } from "node:fs/promises";
import path from "node:path";
import { STORAGE_BUCKETS } from "@/config/limits";
import { listMigrationFiles, MIGRATIONS_DIR } from "@/lib/db/migrate";

const quote = (s: string) => `'${s.replace(/'/g, "''")}'`;

/** The full first-time setup script for pasting into Supabase → SQL Editor. */
export async function buildSetupSql(): Promise<string> {
  // Projects started from a Supabase starter template already have a conflicting `profiles`
  // table and sign-up trigger; this guarded block sets them aside (renames, never deletes).
  const repair = await readFile(
    path.join(MIGRATIONS_DIR, "..", "repair", "legacy-profiles.sql"),
    "utf8",
  );
  const out: string[] = [
    "-- REMAXX first-time setup. Generated by `pnpm db:setup-sql`; do not edit by hand.",
    "-- Paste into Supabase → SQL Editor and click Run.",
    "",
    repair.trim(),
    "",
    "create table if not exists schema_migrations (",
    "  name text primary key,",
    "  applied_at timestamptz not null default now()",
    ");",
    "",
  ];

  const migrations: { name: string; sql: string }[] = [];
  for (const name of await listMigrationFiles()) {
    migrations.push({ name, sql: await readFile(path.join(MIGRATIONS_DIR, name), "utf8") });
  }

  // Pre-check: list every table, type or function a pending migration would create that already
  // exists, all in one error, before anything is created.
  const checks = migrations.flatMap(({ name, sql }) =>
    [...sql.matchAll(/^create (table|type|function) (\w+)/gim)].map((m) => {
      const kind = (m[1] ?? "").toLowerCase();
      const obj = m[2] ?? "";
      const exists =
        kind === "table"
          ? `to_regclass(${quote(`public.${obj}`)}) is not null`
          : kind === "type"
            ? `exists (select 1 from pg_type t join pg_namespace n on n.oid = t.typnamespace where n.nspname = 'public' and t.typname = ${quote(obj)})`
            : `exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'public' and p.proname = ${quote(obj)})`;
      return `  if not exists (select 1 from schema_migrations where name = ${quote(name)}) and ${exists} then clashes := array_append(clashes, ${quote(`${kind} ${obj}`)}::text); end if;`;
    }),
  );
  out.push(
    "-- Pre-check: stop with one clear list if anything REMAXX creates already exists.",
    "do $precheck$",
    "declare clashes text[] := '{}';",
    "begin",
    ...checks,
    "  if array_length(clashes, 1) > 0 then",
    "    raise exception 'These already exist in your database, so REMAXX setup stopped before changing anything: %', array_to_string(clashes, ', ');",
    "  end if;",
    "end",
    "$precheck$;",
    "",
  );

  for (const { name, sql } of migrations) {
    // Each migration runs only if it hasn't been applied yet.
    const tag = `$migration_${name.replace(/\W/g, "_")}$`;
    out.push(
      `-- ${name}`,
      "do $setup$",
      "begin",
      `  if not exists (select 1 from schema_migrations where name = ${quote(name)}) then`,
      `    execute ${tag}`,
      sql.trim(),
      `${tag};`,
      `    insert into schema_migrations (name) values (${quote(name)});`,
      "  end if;",
      "end",
      "$setup$;",
      "",
    );
  }

  out.push("-- Storage buckets");
  for (const b of Object.values(STORAGE_BUCKETS)) {
    const mimes = b.allowedMimeTypes
      ? `array[${b.allowedMimeTypes.map(quote).join(", ")}]`
      : "null";
    out.push(
      "insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)",
      `values (${quote(b.id)}, ${quote(b.id)}, ${b.public}, ${b.fileSizeLimit}, ${mimes})`,
      "on conflict (id) do update set public = excluded.public,",
      "  file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;",
      "",
    );
  }

  out.push("select name as applied_migration from schema_migrations order by name;");
  return out.join("\n") + "\n";
}
