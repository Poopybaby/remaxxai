/**
 * Prints one SQL script that sets up a fresh Supabase project: every migration in db/migrations,
 * the rows that mark them applied (so `pnpm db:migrate` won't re-run them later), and the
 * storage buckets from config/limits.ts.
 *
 * Usage: pnpm db:setup-sql > setup.sql   then paste it into Supabase → SQL Editor → Run.
 * Re-running it on an already set-up project is safe: applied migrations are skipped.
 */
import { readFile } from "node:fs/promises";
import path from "node:path";
import { STORAGE_BUCKETS } from "../config/limits";
import { listMigrationFiles, MIGRATIONS_DIR } from "../lib/db/migrate";

const quote = (s: string) => `'${s.replace(/'/g, "''")}'`;

async function main() {
  const out: string[] = [
    "-- REMAXX first-time setup. Generated by `pnpm db:setup-sql`; do not edit by hand.",
    "-- Paste into Supabase → SQL Editor and click Run.",
    "",
    "create table if not exists schema_migrations (",
    "  name text primary key,",
    "  applied_at timestamptz not null default now()",
    ");",
    "",
  ];

  for (const name of await listMigrationFiles()) {
    const sql = await readFile(path.join(MIGRATIONS_DIR, name), "utf8");
    // Each migration runs only if it hasn't been applied yet.
    const tag = `$migration_${name.replace(/\W/g, "_")}$`;
    out.push(
      `-- ${name}`,
      "do $setup$",
      "begin",
      `  if not exists (select 1 from schema_migrations where name = ${quote(name)}) then`,
      `    execute ${tag}`,
      sql.trim(),
      `${tag};`,
      `    insert into schema_migrations (name) values (${quote(name)});`,
      "  end if;",
      "end",
      "$setup$;",
      "",
    );
  }

  out.push("-- Storage buckets");
  for (const b of Object.values(STORAGE_BUCKETS)) {
    const mimes = b.allowedMimeTypes ? `array[${b.allowedMimeTypes.map(quote).join(", ")}]` : "null";
    out.push(
      "insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)",
      `values (${quote(b.id)}, ${quote(b.id)}, ${b.public}, ${b.fileSizeLimit}, ${mimes})`,
      "on conflict (id) do update set public = excluded.public,",
      "  file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;",
      "",
    );
  }

  out.push("select name as applied_migration from schema_migrations order by name;");
  process.stdout.write(out.join("\n") + "\n");
}

main().catch((err: unknown) => {
  console.error(err);
  process.exit(1);
});
